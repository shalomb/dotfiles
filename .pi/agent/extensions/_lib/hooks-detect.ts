/**
 * Git hook framework detection (shared helper — NOT an extension).
 *
 * Lives in extensions/_lib/ with no index.ts, so pi does not load it as an
 * extension. Extensions import it relatively.
 *
 * Answers, for the repo containing `cwd`: which hook frameworks (pre-commit,
 * husky, lefthook, ...) are configured, which of those are actually installed
 * into git, and what the overall state is. It only reads files and runs
 * read-only git queries; it never installs or changes anything.
 */

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { isAbsolute, join, resolve } from "node:path";

export type Exec = (
	command: string,
	args: string[],
	options?: { cwd?: string; timeout?: number },
) => Promise<{ stdout: string; stderr: string; code: number }>;

export type HooksState = "none" | "configured-not-installed" | "installed";

export interface FrameworkStatus {
	name: string;
	configured: boolean;
	installed: boolean;
	/** Informational frameworks (e.g. commitlint, often CI-only) never affect `state`. */
	informational: boolean;
	evidence: string;
	installHint: string;
}

export interface HooksReport {
	isRepo: boolean;
	repoRoot: string;
	hooksDir: string;
	/** Raw `core.hooksPath` value, or "" when unset. */
	hooksPath: string;
	frameworks: FrameworkStatus[];
	/** Executable, non-.sample files found in the effective hooks directory. */
	nativeHooks: string[];
	/** True when one of our own `pi-gates` dispatcher hooks is installed. */
	piGates: boolean;
	state: HooksState;
}

const GATE_HOOKS = ["pre-commit", "commit-msg", "pre-push"];

function readText(path: string): string {
	try {
		return readFileSync(path, "utf8");
	} catch {
		return "";
	}
}

function readPackageJson(root: string): Record<string, unknown> {
	try {
		return JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as Record<string, unknown>;
	} catch {
		return {};
	}
}

function packageMentions(pkg: Record<string, unknown>, name: string): boolean {
	const deps = (pkg.dependencies ?? {}) as Record<string, unknown>;
	const devDeps = (pkg.devDependencies ?? {}) as Record<string, unknown>;
	return name in deps || name in devDeps || name in pkg;
}

function anyExists(root: string, files: string[]): string | undefined {
	return files.find((f) => existsSync(join(root, f)));
}

function listNativeHooks(hooksDir: string): string[] {
	try {
		return readdirSync(hooksDir).filter((name) => {
			if (name.endsWith(".sample")) return false;
			try {
				const st = statSync(join(hooksDir, name));
				return st.isFile() && (st.mode & 0o111) !== 0;
			} catch {
				return false;
			}
		});
	} catch {
		return [];
	}
}

export async function detectHooks(exec: Exec, cwd: string): Promise<HooksReport> {
	const empty: HooksReport = {
		isRepo: false,
		repoRoot: "",
		hooksDir: "",
		hooksPath: "",
		frameworks: [],
		nativeHooks: [],
		piGates: false,
		state: "none",
	};

	const top = await exec("git", ["rev-parse", "--show-toplevel"], { cwd, timeout: 5000 });
	if (top.code !== 0) return empty;
	const repoRoot = top.stdout.trim();

	const gitPath = await exec("git", ["rev-parse", "--git-path", "hooks"], { cwd: repoRoot, timeout: 5000 });
	let hooksDir = resolve(repoRoot, gitPath.stdout.trim() || ".git/hooks");

	const cfg = await exec("git", ["config", "--get", "core.hooksPath"], { cwd: repoRoot, timeout: 5000 });
	const hooksPath = cfg.code === 0 ? cfg.stdout.trim() : "";
	if (hooksPath) hooksDir = isAbsolute(hooksPath) ? hooksPath : resolve(repoRoot, hooksPath);

	const hookText = (name: string): string => readText(join(hooksDir, name));
	const nativeHooks = listNativeHooks(hooksDir);
	const hooksPathNorm = hooksPath.replace(/^\.\//, "");
	const pkg = readPackageJson(repoRoot);

	const frameworks: FrameworkStatus[] = [];

	const preCommitCfg = anyExists(repoRoot, [".pre-commit-config.yaml", ".pre-commit-config.yml"]);
	frameworks.push({
		name: "pre-commit",
		configured: preCommitCfg !== undefined,
		installed: /pre-commit\.com|INSTALL_PYTHON|generated by pre-commit/i.test(hookText("pre-commit")),
		informational: false,
		evidence: preCommitCfg ?? "no .pre-commit-config.yaml",
		installHint: "pre-commit install",
	});

	const huskyDir = existsSync(join(repoRoot, ".husky"));
	frameworks.push({
		name: "husky",
		configured: huskyDir || packageMentions(pkg, "husky"),
		installed: hooksPathNorm.startsWith(".husky"),
		informational: false,
		evidence: huskyDir ? ".husky/" : packageMentions(pkg, "husky") ? "package.json" : "no husky config",
		installHint: "npx husky (normally run by the package's `prepare` script, i.e. `npm install`)",
	});

	const lefthookCfg = anyExists(repoRoot, [
		"lefthook.yml",
		"lefthook.yaml",
		"lefthook.json",
		".lefthook.yml",
		".lefthook.yaml",
		".lefthook.json",
	]);
	frameworks.push({
		name: "lefthook",
		configured: lefthookCfg !== undefined || packageMentions(pkg, "lefthook"),
		installed: GATE_HOOKS.some((h) => /lefthook/i.test(hookText(h))),
		informational: false,
		evidence: lefthookCfg ?? (packageMentions(pkg, "lefthook") ? "package.json" : "no lefthook config"),
		installHint: "lefthook install",
	});

	const sghCfg = anyExists(repoRoot, [".simple-git-hooks.js", ".simple-git-hooks.cjs", ".simple-git-hooks.json"]);
	const sghConfigured = sghCfg !== undefined || packageMentions(pkg, "simple-git-hooks");
	frameworks.push({
		name: "simple-git-hooks",
		configured: sghConfigured,
		// simple-git-hooks writes bare scripts with no marker, so a present hook only counts as
		// evidence when the repo actually configures it (otherwise it is just a native hook).
		installed: sghConfigured && nativeHooks.includes("pre-commit"),
		informational: false,
		evidence: sghCfg ?? (packageMentions(pkg, "simple-git-hooks") ? "package.json" : "no simple-git-hooks config"),
		installHint: "npx simple-git-hooks",
	});

	const overcommitCfg = anyExists(repoRoot, [".overcommit.yml"]);
	frameworks.push({
		name: "overcommit",
		configured: overcommitCfg !== undefined,
		installed: /overcommit/i.test(hookText("pre-commit")),
		informational: false,
		evidence: overcommitCfg ?? "no .overcommit.yml",
		installHint: "overcommit --install",
	});

	const commitlintCfg = anyExists(repoRoot, [
		"commitlint.config.js",
		"commitlint.config.cjs",
		"commitlint.config.mjs",
		"commitlint.config.ts",
		".commitlintrc",
		".commitlintrc.json",
		".commitlintrc.yml",
		".commitlintrc.yaml",
		".commitlintrc.js",
		".commitlintrc.cjs",
		".commitlintrc.mjs",
		".commitlintrc.ts",
	]);
	frameworks.push({
		name: "commitlint",
		configured: commitlintCfg !== undefined || packageMentions(pkg, "commitlint"),
		installed:
			/commitlint/i.test(hookText("commit-msg")) ||
			(hooksPathNorm.startsWith(".husky") && existsSync(join(repoRoot, ".husky", "commit-msg"))),
		informational: true,
		evidence: commitlintCfg ?? (packageMentions(pkg, "commitlint") ? "package.json" : "no commitlint config"),
		installHint: "(runs from a commit-msg hook of another framework, or CI only)",
	});

	const real = frameworks.filter((f) => !f.informational);
	const anyFrameworkInstalled = real.some((f) => f.installed);
	const anyConfiguredMissing = real.some((f) => f.configured && !f.installed);
	const nativeGate = nativeHooks.some((h) => GATE_HOOKS.includes(h));
	const piGates = GATE_HOOKS.some((h) => hookText(h).includes("pi-gates"));

	let state: HooksState = "none";
	if (anyFrameworkInstalled || nativeGate) state = "installed";
	else if (anyConfiguredMissing) state = "configured-not-installed";

	return { isRepo: true, repoRoot, hooksDir, hooksPath, frameworks, nativeHooks, piGates, state };
}
