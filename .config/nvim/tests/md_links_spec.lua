local L = require("config.md_links")
local tmp = vim.fn.tempname()
vim.fn.mkdir(tmp .. "/docs/sub", "p")
local main, other = tmp .. "/docs/main.md", tmp .. "/docs/sub/other.md"
vim.fn.writefile({ "# Main", "", "[to other](sub/other.md#details)", "## 1.1 Part: One & Two", "end" }, main)
vim.fn.writefile({ "# Other", "text", "## Details", "x", "<a id=\"s2\"></a>", "y" }, other)

describe("md_links.slug (GitHub anchors)", function()
  it("lowercases, strips punctuation, hyphenates", function()
    assert.are.equal("11-part-one--two", L.slug("1.1 Part: One & Two"))
    assert.are.equal("0-at-a-glance", L.slug("0. At a Glance"))
  end)
end)

describe("md_links.link_at", function()
  local line = "see [a](x.md) and [b](https://e.org/p) end"
  it("returns the url of the link under the column", function()
    assert.are.equal("x.md", L.link_at(line, 7))
    assert.are.equal("https://e.org/p", L.link_at(line, 25))
  end)
  it("returns nil off a link", function()
    assert.is_nil(L.link_at(line, 1))
  end)
end)

describe("md_links.resolve", function()
  it("classifies web, anchor and file targets", function()
    assert.are.same({ kind = "web", url = "https://a.b/c" }, L.resolve("https://a.b/c", main))
    assert.are.same({ kind = "anchor", anchor = "foo" }, L.resolve("#foo", main))
    local r = L.resolve("sub/other.md#details", main)
    assert.are.equal("file", r.kind)
    assert.are.equal(other, r.path)
    assert.are.equal("details", r.anchor)
  end)
  it("resolves ../ relative to the buffer dir", function()
    assert.are.equal(main, L.resolve("../main.md", other).path)
  end)
end)

describe("md_links.find_anchor", function()
  it("finds a heading by GitHub slug", function()
    local lines = vim.fn.readfile(main)
    assert.are.equal(4, L.find_anchor(lines, "11-part-one--two"))
  end)
  it("finds an explicit <a id> anchor", function()
    assert.are.equal(5, L.find_anchor(vim.fn.readfile(other), "s2"))
  end)
  it("ignores headings inside code fences", function()
    assert.is_nil(L.find_anchor({ "```", "# nope", "```" }, "nope"))
  end)
  it("returns nil when absent", function()
    assert.is_nil(L.find_anchor({ "# a" }, "zzz"))
  end)
end)

describe("md_links.follow (integration)", function()
  it("opens a relative file and jumps to its anchor", function()
    vim.cmd("edit " .. main)
    vim.api.nvim_win_set_cursor(0, { 3, 3 })
    assert.is_true(L.follow())
    assert.are.equal(other, vim.api.nvim_buf_get_name(0))
    assert.are.equal(3, vim.fn.line("."))
  end)
  it("jumps to an in-file anchor", function()
    vim.cmd("edit " .. main)
    vim.fn.setline(5, "[up](#11-part-one--two)")
    vim.api.nvim_win_set_cursor(0, { 5, 3 })
    assert.is_true(L.follow())
    assert.are.equal(4, vim.fn.line("."))
  end)
  it("hands web links to vim.ui.open", function()
    vim.cmd("edit! " .. main)
    vim.fn.setline(5, "[w](https://e.org/x)")
    local got
    local orig = vim.ui.open
    vim.ui.open = function(u) got = u end
    vim.api.nvim_win_set_cursor(0, { 5, 2 })
    assert.is_true(L.follow())
    vim.ui.open = orig
    assert.are.equal("https://e.org/x", got)
  end)
  it("returns false (so <CR> falls through) when not on a link", function()
    vim.cmd("edit! " .. main)
    vim.api.nvim_win_set_cursor(0, { 1, 0 })
    assert.is_false(L.follow())
  end)
  it("warns and stays put for a missing file", function()
    vim.cmd("edit! " .. main)
    vim.fn.setline(5, "[m](nope.md)")
    vim.api.nvim_win_set_cursor(0, { 5, 2 })
    local warned
    local orig = vim.notify
    vim.notify = function(m) warned = m end
    assert.is_true(L.follow())
    vim.notify = orig
    assert.truthy(warned:match("nope.md"))
    assert.are.equal(main, vim.api.nvim_buf_get_name(0))
  end)
end)
